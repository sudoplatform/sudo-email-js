import { DefaultLogger, Logger } from '@sudoplatform/sudo-common'
import {
  EmailAliasService,
  EmailAliasFilterInput,
  ListEmailAliasesOutput,
} from '../../entities/alias/emailAliasService'

/**
 * Input for `ListEmailAliasesForOwnerUseCase` use case.
 *
 * @interface ListEmailAliasesForOwnerUseCaseInput
 * @property {EmailAliasFilterInput} filter Used to filter results based on properties of the EmailAlias
 * @property {number} limit Number of records to return. If omitted, the limit defaults to 10.
 * @property {string} nextToken A token generated by a previous call to `EmailAliasService.listEmailAliasesForOwner`.
 */
interface ListEmailAliasesForOwnerUseCaseInput {
  filter?: EmailAliasFilterInput
  limit?: number
  nextToken?: string
}

/**
 * Application business logic for listing email aliases for the current owner.
 */
export class ListEmailAliasesForOwnerUseCase {
  private readonly log: Logger

  constructor(private readonly emailAliasService: EmailAliasService) {
    this.log = new DefaultLogger(this.constructor.name)
  }

  async execute(
    input?: ListEmailAliasesForOwnerUseCaseInput,
  ): Promise<ListEmailAliasesOutput> {
    this.log.debug(this.constructor.name, {
      input,
    })

    return await this.emailAliasService.listEmailAliasesForOwner(input)
  }
}
